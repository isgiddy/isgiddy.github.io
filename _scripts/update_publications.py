#!/usr/bin/env python3
"""Refresh _data/publications.yml with Isabelle Giddy's published papers.

Source: ORCID public API (the same records Google Scholar indexes), enriched
with author lists from Crossref. Preprints and other non-journal items are
skipped, so only published papers appear on the site.

Run locally with:  python3 _scripts/update_publications.py
It also runs automatically in the GitHub Pages build (see .github/workflows/jekyll.yml).
If the network is unavailable the existing file is left untouched.
"""
import json, os, sys, urllib.request, urllib.parse

ORCID = "0000-0002-8926-3311"
OUT = os.path.join(os.path.dirname(__file__), "..", "_data", "publications.yml")
HEADERS = {"Accept": "application/json", "User-Agent": "isgiddy.github.io publication updater (mailto:isgiddy@users.noreply.github.com)"}
# Papers without a DOI in ORCID: map exact title -> DOI (optional).
EXTRA_DOIS = {}


def get(url):
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def norm(t):
    return "".join(c for c in t.lower() if c.isalnum())


def crossref(doi):
    try:
        return get("https://api.crossref.org/works/" + urllib.parse.quote(doi))["message"]
    except Exception:
        return None


def crossref_search(title):
    try:
        q = urllib.parse.urlencode({"query.bibliographic": title, "query.author": "Giddy", "rows": 3})
        for it in get("https://api.crossref.org/works?" + q)["message"]["items"]:
            if norm(it.get("title", [""])[0]) == norm(title):
                return it
    except Exception:
        pass
    return None


def fmt_authors(msg):
    names = []
    for a in msg.get("author", []):
        fam, giv = a.get("family", ""), a.get("given", "")
        initials = "".join(p[0] + "." for p in giv.replace("-", " ").split() if p)
        names.append(f"{fam}, {initials}".strip(", "))
    return names


def yq(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    groups = get(f"https://pub.orcid.org/v3.0/{ORCID}/works")["group"]
    pubs, seen = [], set()
    for g in groups:
        s = g["work-summary"][0]
        if s.get("type") != "journal-article":
            continue  # skip preprints, datasets, etc.
        title = s["title"]["title"]["value"]
        if norm(title) in seen:
            continue
        seen.add(norm(title))
        dois = [e["external-id-value"] for e in g["external-ids"]["external-id"] if e["external-id-type"] == "doi"]
        doi = dois[0] if dois else EXTRA_DOIS.get(title)
        msg = crossref(doi) if doi else crossref_search(title)
        if msg and not doi:
            doi = msg.get("DOI")
        pd = s.get("publication-date") or {}
        year = int((pd.get("year") or {}).get("value") or 0)
        journal = (s.get("journal-title") or {}).get("value") or ((msg or {}).get("container-title") or [""])[0]
        pubs.append({
            "title": title.strip(),
            "authors": fmt_authors(msg) if msg else [],
            "journal": journal,
            "year": year,
            "doi": doi or "",
        })
    if not pubs:
        sys.exit("No publications found; leaving existing file untouched.")
    pubs.sort(key=lambda p: (-p["year"], p["title"]))
    lines = ["# Generated by _scripts/update_publications.py from ORCID " + ORCID + ". Edits will be overwritten.", ""]
    for p in pubs:
        lines += [f"- title: {yq(p['title'])}",
                  f"  authors: [{', '.join(yq(a) for a in p['authors'])}]",
                  f"  journal: {yq(p['journal'])}",
                  f"  year: {p['year']}",
                  f"  doi: {yq(p['doi'])}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {len(pubs)} publications to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:  # never break the site build
        print("Publication update skipped:", e)
